"""GhostLine configuration.

Secrets come from the environment (.env, generated by scripts/gen_secrets.sh).
Security parameters live here so they are reviewed in one place.
"""
import os
from datetime import timedelta
from pathlib import Path

BASE_DIR = Path(__file__).resolve().parent


def _require(name: str) -> str:
    value = os.environ.get(name)
    if not value:
        raise RuntimeError(f"Missing required secret {name!r}. Run: bash scripts/gen_secrets.sh")
    return value


def _hex_key(name: str) -> bytes:
    key = bytes.fromhex(_require(name))
    if len(key) != 32:
        raise RuntimeError(f"{name} must be 32 bytes (64 hex chars)")
    return key


class BaseConfig:
    # --- Database ---
    SQLALCHEMY_DATABASE_URI = os.environ.get(
        "DATABASE_URL", f"sqlite:///{BASE_DIR / 'instance' / 'ghostline.db'}"
    )
    SQLALCHEMY_TRACK_MODIFICATIONS = False

    # --- Transport ---
    HOST = os.environ.get("HOST", "127.0.0.1")
    PORT = int(os.environ.get("PORT", "5443"))
    TLS_CERT = os.environ.get("TLS_CERT", str(BASE_DIR / "certs" / "server.crt"))
    TLS_KEY = os.environ.get("TLS_KEY", str(BASE_DIR / "certs" / "server.key"))
    SIGNING_KEY = os.environ.get("SIGNING_KEY", str(BASE_DIR / "certs" / "signing_ed25519.key"))
    PREFERRED_URL_SCHEME = "https"

    # --- Flask's own cookie (only carries the CSRF token) ---
    SESSION_COOKIE_NAME = "__Host-gl_csrf"
    SESSION_COOKIE_SECURE = True
    SESSION_COOKIE_HTTPONLY = True
    SESSION_COOKIE_SAMESITE = "Strict"

    # --- GhostLine server-side sessions ---
    AUTH_COOKIE_NAME = "__Host-gl_session"
    SESSION_IDLE_TIMEOUT = timedelta(minutes=15)
    SESSION_ABSOLUTE_TIMEOUT = timedelta(hours=8)

    # --- Authentication policy ---
    PASSWORD_MIN_LENGTH = 12
    USERNAME_PATTERN = r"^[a-z0-9_]{3,32}$"
    KDF_ITERATIONS = 600_000          # client-side PBKDF2-SHA256 (OWASP 2023+)

    # Server-side Argon2id over the client's auth_key (RFC 9106 "low memory" profile)
    ARGON2_TIME_COST = 3
    ARGON2_MEMORY_KIB = 64 * 1024
    ARGON2_PARALLELISM = 4
    MAX_FAILED_LOGINS = 5
    LOCKOUT_DURATION = timedelta(minutes=15)

    # --- Two-factor authentication (TOTP, RFC 6238) ---
    TOTP_ISSUER = "GhostLine"
    MFA_PENDING_TIMEOUT = timedelta(minutes=5)   # password ok, waiting for the code
    MFA_MAX_FAILURES = 5                         # then the pending session is revoked

    # --- Abuse / rate limits (week 5) ---
    RATELIMIT_ENABLED = True
    RATELIMIT_LOGIN = "10 per minute"        # per IP on prelogin/login/mfa
    RATELIMIT_REGISTER = "5 per hour"        # per IP: throttles mass signup + enumeration
    MAX_STREAMS_PER_USER = 4                 # concurrent live (SSE) connections
    MAX_COUNTER = 2**53 - 1                  # JS-safe integer ceiling for message counters

    # --- Transport / hardening ---
    FORCE_HTTPS = os.environ.get("GHOSTLINE_FORCE_HTTPS", "1") == "1"
    HSTS_MAX_AGE = 365 * 24 * 3600
    MAX_CONTENT_LENGTH = 256 * 1024          # reject oversized request bodies (413)

    # --- Messaging ---
    MESSAGE_TTL_CHOICES = (30, 300, 3600, 86400)  # seconds; None = no self-destruct
    MAX_CIPHERTEXT_B64 = 16_384
    MESSAGE_PAGE_SIZE = 200
    PURGE_INTERVAL_S = 5

    # --- CSRF ---
    WTF_CSRF_TIME_LIMIT = None        # token tied to the session lifetime instead
    WTF_CSRF_SSL_STRICT = True

    def __init__(self):
        self.SECRET_KEY = _require("SECRET_KEY")
        self.AUDIT_HMAC_KEY = _hex_key("AUDIT_HMAC_KEY")
        self.DATA_ENC_KEY = _hex_key("DATA_ENC_KEY")
        self.PRELOGIN_SALT_KEY = _hex_key("PRELOGIN_SALT_KEY")
        self.ALLOWED_ORIGINS = [f"https://localhost:{self.PORT}", f"https://127.0.0.1:{self.PORT}",
                                f"https://ghostline.local:{self.PORT}"]


class DevelopmentConfig(BaseConfig):
    # Off by default: the Werkzeug debugger allows code execution on any 500.
    # Opt in explicitly with GHOSTLINE_DEBUG=1 when you need the traceback locally.
    DEBUG = os.environ.get("GHOSTLINE_DEBUG") == "1"


class ProductionConfig(BaseConfig):
    DEBUG = False


class TestingConfig(BaseConfig):
    TESTING = True
    SQLALCHEMY_DATABASE_URI = "sqlite:///:memory:"
    KDF_ITERATIONS = 1_000            # keep the test suite fast
    ARGON2_TIME_COST = 1
    ARGON2_MEMORY_KIB = 8 * 1024
    ARGON2_PARALLELISM = 1
    SIGNING_KEY = None                # an ephemeral Ed25519 key is generated per test app
    FORCE_HTTPS = False
    # Off by default so unrelated tests aren't throttled; the rate-limit tests pass
    # create_app("testing", RATELIMIT_ENABLED=True). Account lockout is always on.
    RATELIMIT_ENABLED = False

    def __init__(self):
        # Fixed throwaway secrets so tests never depend on a local .env
        for name in ("SECRET_KEY", "AUDIT_HMAC_KEY", "DATA_ENC_KEY", "PRELOGIN_SALT_KEY"):
            os.environ.setdefault(name, "00" * 32)
        super().__init__()


CONFIGS = {
    "development": DevelopmentConfig,
    "production": ProductionConfig,
    "testing": TestingConfig,
}


def get_config(name: str | None = None) -> BaseConfig:
    name = name or os.environ.get("GHOSTLINE_CONFIG", "development")
    try:
        return CONFIGS[name]()
    except KeyError:
        raise RuntimeError(f"Unknown GHOSTLINE_CONFIG {name!r}; choose from {list(CONFIGS)}") from None
